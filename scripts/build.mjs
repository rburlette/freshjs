// Maintainer-only packaging. Both committed entry points are standalone files;
// application authors do not run this script or compile their templates.
import {readFile, writeFile} from 'node:fs/promises';
const core = (await readFile(new URL('../src/fresh-core.js', import.meta.url), 'utf8'))
  .replace('export class freshElement extends HTMLElement', 'class BaseElement extends HTMLElement');
const banner = '// Generated by scripts/build.mjs. Edit src/fresh-core.js; no app build is required.\n';
const expressions = `
export class freshElement extends BaseElement {
\tstatic compileExpression(source, names) {
\t\tconst fields = [...new Set(['item', 'index', ...names])];
\t\tconst evaluate = new Function('{' + fields.join(',') + '}', 'return (' + source + ');');
\t\treturn (self, scope) => evaluate.call(self, scope);
\t}
}
`;
await writeFile(new URL('../fresh.js', import.meta.url), banner + core + expressions);
await writeFile(new URL('../fresh-csp.js', import.meta.url), banner + core + '\nexport {BaseElement as freshElement};\n');
